/// The lit dots of a glyph as (column, row) pairs on the 6 x 8 matrix, with
/// row 0 at the bottom, and the vertical offset in raster units (-4 for
/// lower-case descenders).
pub fn glyph(code: u8) -> (impl Iterator<Item = (u8, u8)>, i16) {
    let c = (code & 0o177) as usize;
    let cols = DOTS[c];
    let (first, drop) = if c >= 0o140 { (1, if cols[0] != 0 { -4 } else { 0 }) } else { (0, 0) };
    let it = (first..6u8).flat_map(move |x| {
        (0..8u8).filter_map(move |y| if cols[x as usize] & (1 << y) != 0 { Some((x, y)) } else { None })
    });
    (it, drop)
}
